//! # Penguins Analysis — Rust Edition
//!
//! Программа на Rust, демонстрирующая ООП, SOLID, макросы, многопоточность
//! и машинное обучение на датасете `penguins.csv`.
//!
//! ## Архитектура (SOLID)
//!
//! - **S**RP — каждый модуль отвечает ровно за одну вещь:
//!   [`io`] читает данные, [`stats`] считает статистику,
//!   [`chart`] рисует гистограмму, [`ml`] обучает классификатор.
//! - **O**CP — новая стратегия очистки данных или новый рендерер диаграмм
//!   добавляются через реализацию соответствующего трейта, без правок
//!   существующего кода (`DropStrategy`, `ChartRenderer`, `Classifier`).
//! - **L**SP — любые реализации этих трейтов взаимозаменяемы в `main`.
//! - **I**SP — трейты узкие: `ChartRenderer` не знает про ML и наоборот.
//! - **D**IP — `main` зависит от трейтов, а конкретные типы внедряются
//!   через конструктор (`CsvDatasetLoader`, `PlottersHistogramRenderer`,
//!   `KnnSpeciesClassifier`).
//!
//! ## ООП
//!
//! ООП в Rust выражается через трейты (интерфейсы) + структуры с инкапсуляцией
//! приватных полей. `Dataset`, `CleanedData`, `HistogramSpec` — объекты
//! значения; `DatasetLoader`, `DropStrategy`, `ChartRenderer`, `Classifier` —
//! полиморфные интерфейсы.
//!
//! ## Макросы
//!
//! В [`macros`] определены собственные декларативные макросы:
//! `dbg_num!`, `assert_count!`, `summary!`.
//!
//! ## Многопоточность
//!
//! Модуль [`threading`] использует `rayon` для параллельного расчёта
//! средних по видам.
//!
//! ## Машинное обучение
//!
//! Модуль [`ml`] обучает KNN-классификатор (smartcore) на числовых
//! признаках пингвина и предсказывает вид.

